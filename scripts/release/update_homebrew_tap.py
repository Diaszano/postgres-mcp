#!/usr/bin/env python3
"""Generates Homebrew Cask and updates Diaszano/homebrew-tap on release."""

from __future__ import annotations

import argparse
import base64
import json
import os
import sys
import urllib.error
import urllib.request
from pathlib import Path


def generate_cask_content(version: str, checksums: dict[str, str], repo: str = "Diaszano/postgres-mcp") -> str:
    """Generate Ruby Cask definition for postgres-mcp standalone binaries."""
    clean_version = version.lstrip("v")
    darwin_amd64 = checksums.get("darwin_amd64", "")
    darwin_arm64 = checksums.get("darwin_arm64", "")
    linux_amd64 = checksums.get("linux_amd64", "")
    linux_arm64 = checksums.get("linux_arm64", "")

    return f"""# This file was auto-generated by postgres-mcp release workflow. DO NOT EDIT.
cask "postgres-mcp" do
  version "{clean_version}"

  on_macos do
    on_intel do
      sha256 "{darwin_amd64}"
      url "https://github.com/{repo}/releases/download/v#{{version}}/postgres-mcp_#{{version}}_darwin_amd64.tar.gz"
    end
    on_arm do
      sha256 "{darwin_arm64}"
      url "https://github.com/{repo}/releases/download/v#{{version}}/postgres-mcp_#{{version}}_darwin_arm64.tar.gz"
    end
  end

  on_linux do
    on_intel do
      sha256 "{linux_amd64}"
      url "https://github.com/{repo}/releases/download/v#{{version}}/postgres-mcp_#{{version}}_linux_amd64.tar.gz"
    end
    on_arm do
      sha256 "{linux_arm64}"
      url "https://github.com/{repo}/releases/download/v#{{version}}/postgres-mcp_#{{version}}_linux_arm64.tar.gz"
    end
  end

  name "postgres-mcp"
  desc "PostgreSQL Tuning and Analysis Tool (MCP Server)"
  homepage "https://github.com/{repo}"

  livecheck do
    skip "Auto-generated on release."
  end

  binary "postgres-mcp"

  # No zap stanza required
end
"""


def load_checksums_from_dir(dist_dir: Path, version: str) -> dict[str, str]:
    """Read sha256 checksums from .sha256 files in directory."""
    clean_version = version.lstrip("v")
    checksums: dict[str, str] = {}
    for platform in ["darwin_amd64", "darwin_arm64", "linux_amd64", "linux_arm64"]:
        sha_file = dist_dir / f"postgres-mcp_{clean_version}_{platform}.tar.gz.sha256"
        if sha_file.exists():
            first_line = sha_file.read_text(encoding="utf-8").strip().splitlines()[0]
            checksums[platform] = first_line.split()[0]
    return checksums


def push_to_homebrew_tap(cask_content: str, version: str, tap_repo: str = "Diaszano/homebrew-tap", token: str | None = None) -> bool:
    """Commit and push Cask to tap repo via GitHub REST API."""
    if not token:
        print("Notice: No HOMEBREW_TAP_TOKEN provided. Skipping automated remote push.", file=sys.stderr)
        return False

    clean_version = version.lstrip("v")
    path = "Casks/postgres-mcp.rb"
    api_url = f"https://api.github.com/repos/{tap_repo}/contents/{path}"
    headers = {
        "Authorization": f"Bearer {token}",
        "Accept": "application/vnd.github.v3+json",
        "User-Agent": "postgres-mcp-release-bot",
    }

    current_sha: str | None = None
    try:
        req = urllib.request.Request(api_url, headers=headers)
        with urllib.request.urlopen(req) as resp:
            data = json.loads(resp.read().decode())
            current_sha = data.get("sha")
    except urllib.error.HTTPError as e:
        if e.code != 404:
            print(f"Warning: Failed to query existing cask on tap: {e}", file=sys.stderr)

    payload = {
        "message": f"chore(release): update postgres-mcp to v{clean_version}",
        "content": base64.b64encode(cask_content.encode("utf-8")).decode("ascii"),
        "branch": "main",
    }
    if current_sha:
        payload["sha"] = current_sha

    data_bytes = json.dumps(payload).encode("utf-8")
    req = urllib.request.Request(api_url, data=data_bytes, headers=headers, method="PUT")
    try:
        with urllib.request.urlopen(req) as resp:
            if resp.status in (200, 201):
                print(f"✅ Successfully updated {path} in {tap_repo} to v{clean_version}")
                return True
    except urllib.error.HTTPError as e:
        print(f"Error: Failed to push cask to {tap_repo}: {e.read().decode()}", file=sys.stderr)
        return False
    return False


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate and update Homebrew Tap Cask")
    parser.add_argument("--version", required=True, help="Release version (e.g. 0.4.2)")
    parser.add_argument("--dist-dir", type=Path, default=Path("dist"), help="Directory containing .sha256 files")
    parser.add_argument("--tap-repo", default="Diaszano/homebrew-tap", help="Target tap repo")
    parser.add_argument("--output", type=Path, default=Path("dist/postgres-mcp.rb"), help="Output path for cask file")
    parser.add_argument("--push", action="store_true", help="Push to remote tap repository if token available")
    args = parser.parse_args()

    checksums = load_checksums_from_dir(args.dist_dir, args.version)
    cask_text = generate_cask_content(args.version, checksums)

    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(cask_text, encoding="utf-8")
    print(f"Saved Cask definition to: {args.output}")

    if args.push:
        token = os.environ.get("HOMEBREW_TAP_TOKEN") or os.environ.get("GH_PAT")
        push_to_homebrew_tap(cask_text, args.version, tap_repo=args.tap_repo, token=token)

    return 0


if __name__ == "__main__":
    sys.exit(main())
